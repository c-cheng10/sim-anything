def test_unknown_masses_scaled_to_total():
    spec = _spec("toy_6dof_dh")  # no link masses at all
    m = _model("toy_6dof_dh")
    assert m.body_mass.sum() == pytest.approx(spec.total_mass, rel=1e-6)
    # without total_mass: volume x 1000 kg/m^3
    m2 = mujoco.MjModel.from_xml_string(build_mjcf(spec.model_copy(update={"total_mass": None})))
    vol = 0.0
    for g in range(m2.ngeom):
        assert m2.geom_type[g] in (mujoco.mjtGeom.mjGEOM_CAPSULE, mujoco.mjtGeom.mjGEOM_CYLINDER)
        r, h = m2.geom_size[g][:2]
        vol += math.pi * r * r * 2 * h + (4 / 3 * math.pi * r ** 3 if m2.geom_type[g] == mujoco.mjtGeom.mjGEOM_CAPSULE
                                           else 0.0)
    assert m2.body_mass.sum() == pytest.approx(1000 * vol, rel=1e-6)


@pytest.mark.parametrize("name", EXAMPLES)
def test_hold_home_and_no_self_collision(name):
    spec = _spec(name).to_si()
    m = _model(name)
    d = mujoco.MjData(m)
    mujoco.mj_resetDataKeyframe(m, d, m.key("home").id)
    mujoco.mj_forward(m, d)
    assert all(c.dist > -1e-3 for c in d.contact[: d.ncon])
    q0 = d.qpos.copy()
    drift = 0.0
    while d.time < 2.0:
        mujoco.mj_step(m, d)
        drift = max(drift, float(np.max(np.abs(d.qpos - q0))))
    assert np.all(np.isfinite(d.qpos))
    assert not any(w.number for w in d.warning)
    for i, j in enumerate(spec.joints):
        assert abs(d.qpos[i] - q0[i]) < (0.05 if j.type == "hinge" else 0.005)
    assert drift < 0.05
    assert np.max(np.abs(d.qvel)) < 0.1


def test_units_mm_deg_equal_m_rad():
    spec = _spec("toy_6dof_dh")
    deg = math.pi / 180
    rows = [(0, 90, 0.15), (-0.4, 0, 0), (-0.35, 0, 0), (0, 90, 0.12), (0, -90, 0.1), (0, 0, 0.1)]
    lims = [360, 360, 180, 360, 360, 360]
    efforts = [150, 150, 150, 28, 28, 28]
    joints = [Joint(name=f"j{i + 1}", dh=DH(a=a, alpha=al * deg, d=dd),
                    limits={"lower": -lim * deg, "upper": lim * deg}, effort_limit=e)
              for i, ((a, al, dd), lim, e) in enumerate(zip(rows, lims, efforts))]
    si = Spec(name="toy_6dof_dh", manufacturer=spec.manufacturer, dof=6, units=Units(length="m", angle="rad"),
              convention="dh_standard", joints=joints, ee=spec.ee, total_mass=18,
              reach={"value": 0.85, "measured_from": "base_axis_horizontal"}, estimates=spec.estimates)
    assert build_mjcf(si) == _xml("toy_6dof_dh")
    # and to_si() of the mm/deg spec too
    assert build_mjcf(spec.to_si()) == _xml("toy_6dof_dh")


