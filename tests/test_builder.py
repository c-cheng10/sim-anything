import math
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco
import numpy as np
import pytest

from simanything.builder import build_file, build_mjcf
from simanything.spec import DH, Joint, Spec, Units, dh_fk, load_spec

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ["toy_2link", "toy_6dof_dh", "toy_6dof_mdh", "toy_scara"]


def _spec(name: str) -> Spec:
    return load_spec(ROOT / "examples" / f"{name}.yaml")


_CACHE: dict[str, str] = {}


def _xml(name: str) -> str:
    if name not in _CACHE:
        _CACHE[name] = build_mjcf(_spec(name))
    return _CACHE[name]


def _model(name: str) -> mujoco.MjModel:
    return mujoco.MjModel.from_xml_string(_xml(name))


def _ee_world(model, data, site, q) -> np.ndarray:
    data.qpos[:] = q
    mujoco.mj_kinematics(model, data)
    s = model.site(site).id
    T = np.eye(4)
    T[:3, :3] = data.site_xmat[s].reshape(3, 3)
    T[:3, 3] = data.site_xpos[s]
    return T


def _random_q(spec: Spec, rng, n=10):
    si = spec.to_si()
    lo = [j.limits.lower if j.limits else -math.pi for j in si.joints]
    hi = [j.limits.upper if j.limits else math.pi for j in si.joints]
    return [rng.uniform(lo, hi) for _ in range(n)]


@pytest.mark.parametrize("name", EXAMPLES)
def test_compiles_and_structure(name):
    spec = _spec(name).to_si()
    m = _model(name)
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    assert np.all(np.isfinite(d.qacc))
    assert m.body(1).name == "base"
    assert m.opt.timestep <= 0.002
    # joints: names, types, order, ranges
    assert m.njnt == spec.dof
    for i, j in enumerate(spec.joints):
        assert m.joint(i).name == j.name
        assert m.jnt_type[i] == (mujoco.mjtJoint.mjJNT_HINGE if j.type == "hinge" else mujoco.mjtJoint.mjJNT_SLIDE)
        if j.limits:
            assert m.jnt_limited[i]
            assert np.allclose(m.jnt_range[i], [j.limits.lower, j.limits.upper], atol=1e-9)
        # bodies nested in chain order
        expected_body = j.link.name or f"{j.name}_link"
        assert m.body(m.jnt_bodyid[i]).name == expected_body
        assert m.body_parentid[m.jnt_bodyid[i]] == (1 if i == 0 else m.jnt_bodyid[i - 1])
    # actuators: one position servo per joint
    assert m.nu == spec.dof
    for i, j in enumerate(spec.joints):
        a = m.actuator(f"{j.name}_act")
        assert m.actuator_trnid[a.id, 0] == i
        assert m.actuator_gainprm[a.id, 0] > 0 and m.actuator_biasprm[a.id, 1] == -m.actuator_gainprm[a.id, 0]
        if j.limits:
            assert np.allclose(m.actuator_ctrlrange[a.id], [j.limits.lower, j.limits.upper], atol=1e-9)
        if j.effort_limit:
            assert np.allclose(m.actuator_forcerange[a.id], [-j.effort_limit, j.effort_limit])
    # EE site on the last body; home keyframe
    s = m.site(spec.ee.name)
    assert s.bodyid[0] == m.jnt_bodyid[spec.dof - 1]
    k = m.key("home")
    assert np.allclose(k.qpos, [j.home for j in spec.joints], atol=1e-9)
    assert np.allclose(k.ctrl, [j.home for j in spec.joints], atol=1e-9)
    assert f"Generated by sim-anything from spec '{spec.name}'" in _xml(name)


@pytest.mark.parametrize("name", EXAMPLES)
def test_fk_matches_chain(name):
    spec = _spec(name)
    ch = spec.chain()
    m = _model(name)
    d = mujoco.MjData(m)
    for q in [np.zeros(spec.dof)] + _random_q(spec, np.random.default_rng(3)):
        T = _ee_world(m, d, spec.ee.name, q)
        Tc = ch.fk(q)
        assert np.allclose(T[:3, 3], Tc[:3, 3], atol=1e-8)
        assert np.allclose(T[:3, :3], Tc[:3, :3], atol=1e-8)


def test_fk_hand_computed_planar_2link():
    # shoulder at (0, 0, 0.1), both joints about +y, links 0.3 and 0.25 along x.
    # A rotation by q about +y maps x to (cos q, 0, -sin q).
    m = _model("toy_2link")
    d = mujoco.MjData(m)
    for q1, q2 in [(0, 0), (math.pi / 2, 0), (0.3, -0.7), (-1.2, 2.0), (math.pi / 4, math.pi / 4)]:
        x = 0.3 * math.cos(q1) + 0.25 * math.cos(q1 + q2)
        z = 0.1 - 0.3 * math.sin(q1) - 0.25 * math.sin(q1 + q2)
        p = _ee_world(m, d, "ee_site", [q1, q2])[:3, 3]
        assert np.allclose(p, [x, 0, z], atol=1e-9)


def test_fk_dh_examples_match_textbook():
    for name in ["toy_6dof_dh", "toy_6dof_mdh"]:
        spec = _spec(name)
        si = spec.to_si()
        m = _model(name)
        d = mujoco.MjData(m)
        for q in _random_q(spec, np.random.default_rng(7), 5):
            T = _ee_world(m, d, spec.ee.name, q)
            Tdh = dh_fk([j.dh for j in si.joints], q, si.convention)
            Tdh[:3, 3] += Tdh[:3, :3] @ np.array(si.ee.origin.xyz)
            assert np.allclose(T[:3, 3], Tdh[:3, 3], atol=1e-8)


def test_fk_hand_computed_6dof_dh_home():
    # UR-like standard DH at q = 0: x = a2 + a3 = -0.75, y = -(d4 + d6) = -0.22, z = d1 - d5 = 0.05
    m = _model("toy_6dof_dh")
    d = mujoco.MjData(m)
    p = _ee_world(m, d, "ee_site", np.zeros(6))[:3, 3]
    assert np.allclose(p, [-0.75, -0.22, 0.05], atol=1e-9)


@pytest.mark.parametrize("name", EXAMPLES)
def test_inertia_valid_and_total_mass(name):
    spec = _spec(name)
    m = _model(name)
    for b in range(1, m.nbody):
        I = m.body_inertia[b]
        assert m.body_mass[b] > 0
        assert np.all(I > 0)
        A, B, C = sorted(I)
        assert A + B >= C - 1e-9
    if spec.total_mass:
        assert m.body_mass.sum() == pytest.approx(spec.total_mass, rel=1e-6)


